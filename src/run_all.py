"""Run every query in sql/ against the schema with SQLite, check the known answers, and write answers/results.md.

Run: python src/run_all.py
"""
import json, os, sqlite3
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db = sqlite3.connect(":memory:")
db.executescript(open(os.path.join(ROOT, "sql", "schema.sql")).read())
index = json.load(open(os.path.join(ROOT, "sql", "index.json")))
expected = json.load(open(os.path.join(ROOT, "answers", "expected.json")))
out, fails = ["# Results\n", "Generated by `src/run_all.py` (SQLite).\n"], 0
for q in index:
    sql = open(os.path.join(ROOT, "sql", q["file"])).read()
    cur = db.execute(sql); cols = [c[0] for c in cur.description]; rows = [list(r) for r in cur.fetchall()]
    ok = q["id"] not in expected or rows == expected[q["id"]]
    fails += not ok
    out += [f"\n## {q['id'].upper()} · {q['question']}  {'✅' if ok else '❌'}\n", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    print(("PASS" if ok else "FAIL"), q["id"], rows if not ok else "")
open(os.path.join(ROOT, "answers", "results.md"), "w").write("\n".join(out) + "\n")
raise SystemExit(1 if fails else 0)
